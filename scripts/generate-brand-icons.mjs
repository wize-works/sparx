/**
 * Regenerate every sparx favicon / app icon from the brand geometry.
 *
 *   node scripts/generate-brand-icons.mjs
 *
 * The ONE source of truth is sparx/packages/brand/src/marks.ts — this script parses the
 * field path + brand hexes straight out of it, so the static files can never
 * drift from the vector components. Change the artwork there, re-run this, done.
 * Nothing here is generated on the fly at build time: favicons must be byte-stable
 * files a CDN can cache, and .ico/.png are not formats a React component emits.
 *
 * Requires `sharp`, which is already in the lockfile via services/media-worker;
 * it is resolved from there so this needs no root dependency and no install. Run
 * it with a plain `node` — no pnpm filter needed.
 *
 * The mark: a full-bleed field of brand color with the "x" knocked out of it.
 * In vector form the counter is genuinely transparent; every raster here backs it
 * with sparx ink so the icon reads identically in a browser tab, on an iOS home
 * screen, and in an Android install tile.
 */

import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// sharp ships prebuilt platform binaries, so it is never hoisted to the root of a
// pnpm workspace. Resolve it from the one package that depends on it.
const require = createRequire(join(ROOT, 'wizeworks/services/media-worker/package.json'));
let sharp;
try {
  sharp = require('sharp');
} catch {
  console.error(
    'sharp not found. Run `pnpm install` first — it is a dependency of services/media-worker.'
  );
  process.exit(1);
}

// ── Geometry + color, read from sparx/packages/brand/src/marks.ts ──────────────────
// Parsed rather than imported: marks.ts is TypeScript, and this script must run
// under a bare `node` with no build step or loader in the way.

const marks = readFileSync(join(ROOT, 'sparx/packages/brand/src/marks.ts'), 'utf8');

/** Pull a `export const NAME = '…'` (or a `+`-concatenated string) out of marks.ts. */
function constant(name) {
  const m = marks.match(new RegExp(`export const ${name}[^=]*=\\s*([\\s\\S]*?);\\n`));
  if (!m) throw new Error(`marks.ts: could not find export const ${name}`);
  return [...m[1].matchAll(/'([^']*)'/g)].map((s) => s[1]).join('');
}

/** Pull a hex out of the `BRAND` object literal. */
function brandHex(key) {
  const m = marks.match(new RegExp(`${key}:\\s*'(#[0-9a-fA-F]{6})'`));
  if (!m) throw new Error(`marks.ts: could not find BRAND.${key}`);
  return m[1];
}

const FIELD_PATH = constant('ICON_FIELD_PATH'); // the knockout tile
const MARK_PATH = constant('SPARK_PATH'); // the standalone "x"
const EMBER = brandHex('primary');
const INK = brandHex('ink');
const PAPER = brandHex('paper');

// ── SVG builders ─────────────────────────────────────────────────────────────

const GENERATED = '<!-- Generated by scripts/generate-brand-icons.mjs — do not hand-edit. -->';

/**
 * The app icon: the field, with the "x" showing through as negative space.
 * `counter` of `null` leaves the counter truly transparent (one-color press
 * artwork, meant to sit on a known surface).
 */
function tileSvg({ field, counter }) {
  const back = counter ? `\n  <rect width="160" height="160" fill="${counter}"/>` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 160" width="160" height="160">
  ${GENERATED}${back}
  <path d="${FIELD_PATH}" fill="${field}"/>
</svg>
`;
}

/** The standalone "x" on transparency — the inline mark, not the app icon. */
function markSvg(color) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 160" width="160" height="160">
  ${GENERATED}
  <path d="${MARK_PATH}" fill="${color}"/>
</svg>
`;
}

/**
 * The maskable PWA tile. Android crops maskable icons to an arbitrary shape and
 * only guarantees the centre 80% circle, which would eat the knockout's corners —
 * so this variant inverts the treatment: a solid field that survives any mask,
 * with the POSITIVE "x" inset well inside the safe zone.
 */
function maskableSvg() {
  // Android's guaranteed safe area is the centre circle of radius 40% — 64 of 160.
  // The "x" is widest at its four arm tips, i.e. the corners of its own bounding
  // box (110.89 × 103.25 inside the viewBox), so the binding constraint is that
  // box's half-diagonal: 75.75 × scale must land on 64. That gives 0.845, an "x"
  // ~59% of the tile — the usual maskable proportion, and nothing to clip.
  const scale = 64 / 75.75;
  const inset = (160 * (1 - scale)) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 160" width="160" height="160">
  ${GENERATED}
  <rect width="160" height="160" fill="${EMBER}"/>
  <g transform="translate(${inset} ${inset}) scale(${scale.toFixed(4)})">
    <path d="${MARK_PATH}" fill="${INK}"/>
  </g>
</svg>
`;
}

// ── Raster helpers ───────────────────────────────────────────────────────────

const OPAQUE_TILE = tileSvg({ field: EMBER, counter: INK });

/**
 * Rasterize an SVG string at `size`px square.
 *
 * Density is set so the renderer draws the vector AT the target size — do not
 * "improve" this by rendering large and downsampling. The mark is nothing but
 * long diagonals, and a supersampled downsample gives them a visible halo at
 * 16px where rasterizing once at 16px stays crisp.
 */
async function png(svg, size) {
  return sharp(Buffer.from(svg), { density: (72 * size) / 160 })
    .resize(size, size)
    .png({ compressionLevel: 9 })
    .toBuffer();
}

/**
 * A multi-resolution Windows .ico with PNG-encoded entries.
 *
 * 6-byte header, one 16-byte directory entry per image, then the PNG blobs — the
 * same container the public favicon tool builds (see
 * sparx/apps/web/components/marketing/tools/lib/ico.ts). Modern browsers and Windows
 * (Vista+) read PNG inside .ico, so there is no BMP fallback to write.
 */
function ico(images) {
  const header = Buffer.alloc(6 + images.length * 16);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: 1 = icon
  header.writeUInt16LE(images.length, 4);

  let offset = header.length;
  images.forEach(({ size, data }, i) => {
    const e = 6 + i * 16;
    header.writeUInt8(size >= 256 ? 0 : size, e); // width (256 encodes as 0)
    header.writeUInt8(size >= 256 ? 0 : size, e + 1); // height
    header.writeUInt8(0, e + 2); // palette size (0 = no palette)
    header.writeUInt8(0, e + 3); // reserved
    header.writeUInt16LE(1, e + 4); // color planes
    header.writeUInt16LE(32, e + 6); // bits per pixel
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });

  return Buffer.concat([header, ...images.map((i) => i.data)]);
}

const written = [];
function write(relPath, data) {
  const full = join(ROOT, relPath);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, data);
  written.push(relPath);
}

// ── The output set ───────────────────────────────────────────────────────────

async function main() {
  const faviconIco = ico([
    { size: 16, data: await png(OPAQUE_TILE, 16) },
    { size: 32, data: await png(OPAQUE_TILE, 32) },
    { size: 48, data: await png(OPAQUE_TILE, 48) },
  ]);
  const maskable512 = await png(maskableSvg(), 512);

  // Apps whose icons Next serves from the app/ directory convention.
  for (const app of ['sparx/apps/web', 'sparx/apps/workbench']) {
    write(`${app}/app/icon.svg`, OPAQUE_TILE);
    write(`${app}/app/favicon.ico`, faviconIco);
    write(`${app}/app/apple-icon.png`, await png(OPAQUE_TILE, 180));
  }

  // sparx/apps/web additionally ships the explicit PWA + legacy-link set that
  // app/manifest.ts and the head links reference by name.
  write('sparx/apps/web/app/apple-touch-icon.png', await png(OPAQUE_TILE, 180));
  write('sparx/apps/web/app/favicon-16x16.png', await png(OPAQUE_TILE, 16));
  write('sparx/apps/web/app/favicon-32x32.png', await png(OPAQUE_TILE, 32));
  write('sparx/apps/web/app/favicon-48x48.png', await png(OPAQUE_TILE, 48));
  write('sparx/apps/web/app/icon-192.png', await png(OPAQUE_TILE, 192));
  write('sparx/apps/web/app/icon-512.png', await png(OPAQUE_TILE, 512));
  write('sparx/apps/web/app/maskable-512.png', maskable512);
  write('sparx/apps/web/public/android-chrome-192x192.png', await png(OPAQUE_TILE, 192));
  write('sparx/apps/web/public/android-chrome-512x512.png', await png(OPAQUE_TILE, 512));
  write('sparx/apps/web/public/maskable-512.png', maskable512);
  write('sparx/apps/web/public/icon.png', await png(OPAQUE_TILE, 512));

  // Press-ready artwork behind the /brand download page, in the same four-variant
  // scheme the wordmark uses (color / light-for-dark / one-color black / one-color
  // white). `sparx-mark-*` is the standalone "x"; `sparx-app-icon-*` is the tile.
  //
  // The tile's two one-color variants keep a genuinely transparent counter — that
  // is what one-color MEANS for a knockout mark: the surface shows through the "x".
  write('sparx/apps/web/public/brand/sparx-favicon.ico', faviconIco);
  write('sparx/apps/web/public/brand/sparx-mark.svg', markSvg(EMBER));
  write('sparx/apps/web/public/brand/sparx-mark-light.svg', markSvg(PAPER));
  write('sparx/apps/web/public/brand/sparx-mark-black.svg', markSvg(INK));
  write('sparx/apps/web/public/brand/sparx-mark-white.svg', markSvg(PAPER));
  write('sparx/apps/web/public/brand/sparx-mark.png', await png(markSvg(EMBER), 512));
  write('sparx/apps/web/public/brand/sparx-app-icon.svg', tileSvg({ field: EMBER, counter: INK }));
  write(
    'sparx/apps/web/public/brand/sparx-app-icon-light.svg',
    tileSvg({ field: EMBER, counter: PAPER })
  );
  write(
    'sparx/apps/web/public/brand/sparx-app-icon-black.svg',
    tileSvg({ field: INK, counter: null })
  );
  write(
    'sparx/apps/web/public/brand/sparx-app-icon-white.svg',
    tileSvg({ field: PAPER, counter: null })
  );
  write('sparx/apps/web/public/brand/sparx-app-icon.png', await png(OPAQUE_TILE, 512));

  // market + site link their icons from public/ explicitly (see each app/layout.tsx).
  // On wizeworks/apps/site these are the FALLBACK a tenant site wears until it uploads its
  // own favicon — deliberately favicon-only, so sparx never brands a tenant's
  // home-screen install.
  for (const app of ['sparx/apps/market', 'wizeworks/apps/site']) {
    write(`${app}/public/favicon.ico`, faviconIco);
    write(`${app}/public/sparx-icon.svg`, OPAQUE_TILE);
  }

  // The designer's delivery kit, kept in step so images/ never shows retired art.
  write('images/new/favicons/favicon.ico', faviconIco);
  write('images/new/favicons/favicon-16x16.png', await png(OPAQUE_TILE, 16));
  write('images/new/favicons/favicon-32x32.png', await png(OPAQUE_TILE, 32));
  write('images/new/favicons/favicon-48x48.png', await png(OPAQUE_TILE, 48));
  write('images/new/favicons/apple-touch-icon.png', await png(OPAQUE_TILE, 180));
  write('images/new/favicons/icon-192.png', await png(OPAQUE_TILE, 192));
  write('images/new/favicons/icon-512.png', await png(OPAQUE_TILE, 512));
  write('images/new/favicons/maskable-512.png', maskable512);
  write('images/new/favicons/icon.svg', OPAQUE_TILE);
  write('images/new/favicons/mark.svg', markSvg(EMBER));

  console.log(`Wrote ${written.length} files:`);
  for (const f of written) console.log(`  ${f}`);
}

await main();
